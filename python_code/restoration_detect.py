def resize_keep_ratio_for_ocr(pil_img, target_h=128):
    img = pil_img.convert("RGB")
    w, h = img.size

    scale = target_h / h
    new_w = int(w * scale)

    return img.resize((new_w, target_h), Image.BICUBIC)

def clahe_gray_for_ocr(pil_img, clip=1.5):
    img = np.array(pil_img.convert("RGB"))
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

    clahe = cv2.createCLAHE(clipLimit=clip, tileGridSize=(8, 8))
    gray = clahe.apply(gray)

    return Image.fromarray(gray).convert("RGB")

def sharpen_soft(pil_img, amount=1.15, sigma=0.8):
    img = np.array(pil_img.convert("RGB"))
    blur = cv2.GaussianBlur(img, (0, 0), sigma)
    sharp = cv2.addWeighted(img, amount, blur, 1 - amount, 0)
    sharp = np.clip(sharp, 0, 255).astype(np.uint8)

    return Image.fromarray(sharp)

