def expand_box(x1, y1, x2, y2, img_w, img_h, scale_x=1.8, scale_y=1.8):
    bw = x2 - x1
    bh = y2 - y1
    cx = (x1 + x2) / 2
    cy = (y1 + y2) / 2

    new_w = bw * scale_x
    new_h = bh * scale_y

    nx1 = int(max(0, cx - new_w / 2))
    ny1 = int(max(0, cy - new_h / 2))
    nx2 = int(min(img_w, cx + new_w / 2))
    ny2 = int(min(img_h, cy + new_h / 2))

    return nx1, ny1, nx2, ny2


def plate_quality_score(crop, conf):
    if crop is None or crop.size == 0:
        return -999

    gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape[:2]
    area = w * h
    aspect = w / max(1, h)
    sharpness = cv2.Laplacian(gray, cv2.CV_64F).var()
    brightness = gray.mean()
    contrast = gray.std()

    score = 0

   # 번호판 크기별 가산점 점수 부여. 크기가 클수록 좋은 점수.
    if w >= 80 and h >= 25:
        score += 25
    elif w >= 45 and h >= 14:
        score += 10
    else:
        score -= 15

   #가로세로비율(종횡비) 평가
    if 1.4 <= aspect <= 8.5:
        score += 25
    else:
        score -= 10

    #선명도 및 대비 점수 추가
    score += min(sharpness / 5, 45)
    score += min(contrast, 35)


    #밝기 적정성 평가
    if 25 <= brightness <= 235:
        score += 15
    else:
        score -= 10

    #면적이 너무 작은경우 감점
    if area < 500:
        score -= 15

# YOLO 신뢰도 점수 반영
    score += conf * 40
    return score


