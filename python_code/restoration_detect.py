class FPNMobileNetGenerator(nn.Module):
    def __init__(self):
        super(FPNMobileNetGenerator, self).__init__()

        # 학습 당시 코드와 동일: torchvision MobileNetV2 backbone 사용
        backbone = models.mobilenet_v2(weights=None).features

        self.enc1 = backbone[0:2]   # 16 channels
        self.enc2 = backbone[2:4]   # 24 channels
        self.enc3 = backbone[4:7]   # 32 channels
        self.enc4 = backbone[7:14]  # 96 channels

        self.lateral4 = nn.Conv2d(96, 64, 1)
        self.lateral3 = nn.Conv2d(32, 64, 1)
        self.lateral2 = nn.Conv2d(24, 64, 1)

        self.smooth = nn.Conv2d(64, 64, 3, padding=1)

        # 학습 당시 AIHub 코드와 동일: SiLU + Tanh
        self.head = nn.Sequential(
            nn.Conv2d(64, 32, 3, padding=1),
            nn.SiLU(inplace=True),
            nn.Conv2d(32, 3, 3, padding=1),
            nn.Tanh()
        )

    def forward(self, x):
        feat1 = self.enc1(x)
        feat2 = self.enc2(feat1)
        feat3 = self.enc3(feat2)
        feat4 = self.enc4(feat3)

        p4 = self.lateral4(feat4)
        p3 = self.lateral3(feat3) + F.interpolate(p4, scale_factor=2, mode="nearest")
        p2 = self.lateral2(feat2) + F.interpolate(p3, scale_factor=2, mode="nearest")

        out = self.smooth(p2)

        # 학습 당시 코드와 동일: scale_factor=4, nearest
        out = F.interpolate(out, scale_factor=4, mode="nearest")

        return self.head(out)

