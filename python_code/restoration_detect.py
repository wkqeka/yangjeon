def deblur_one_bgr(img_bgr):
    """번호판 이미지를 DeblurGAN으로 복원하고 원래 비율로 변환한다."""

    original_h, original_w = img_bgr.shape[:2]

    rgb = cv2.cvtColor(
        img_bgr,
        cv2.COLOR_BGR2RGB
    )
    pil_img = Image.fromarray(rgb)

    x = (
        to_tensor_exact(pil_img)
        .unsqueeze(0)
        .to(device)
    )

    deblur_model.eval()

    with torch.no_grad():
        y = deblur_model(x)

    y = y.detach().cpu().squeeze(0)
    y = (y * 0.5 + 0.5).clamp(0, 1)
    y = y.permute(1, 2, 0).numpy()

    restored_rgb = (y * 255).astype(np.uint8)

    # 256x256 letterbox에서 실제 번호판 영역만 추출
    scale = min(
        256 / max(original_w, 1),
        256 / max(original_h, 1)
    )

    content_w = max(1, int(original_w * scale))
    content_h = max(1, int(original_h * scale))

    left = (256 - content_w) // 2
    top = (256 - content_h) // 2

    restored_rgb = restored_rgb[
        top:top + content_h,
        left:left + content_w
    ]

    # 원래 번호판 크기로 복원
    restored_rgb = cv2.resize(
        restored_rgb,
        (original_w, original_h),
        interpolation=cv2.INTER_CUBIC
    )

    return cv2.cvtColor(
        restored_rgb,
        cv2.COLOR_RGB2BGR
    )

def laplacian_variance(img):
    """윤곽의 선명도를 라플라시안 분산으로 계산한다."""

    gray = cv2.cvtColor(
        img,
        cv2.COLOR_BGR2GRAY
    )

    return float(
        cv2.Laplacian(
            gray,
            cv2.CV_64F
        ).var()
    )

